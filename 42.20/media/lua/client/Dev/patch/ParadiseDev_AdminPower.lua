
function ISPVPLogToolUI:onTicked(index, selected)
--[[ 
    if index == 1 then
        SendCommandToServer("/changeoption PVPLogToolChat \"" .. tostring(selected) .. "\"")
    end
    if index == 2 then
        SendCommandToServer("/changeoption PVPLogToolFile \"" .. tostring(selected) .. "\"")
    end
 ]]
end
