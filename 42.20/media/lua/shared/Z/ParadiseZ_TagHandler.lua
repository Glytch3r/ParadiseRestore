ParadiseZ = ParadiseZ or {}
ParadiseZ.suspectTags = ParadiseZ.suspectTags or {}

if isServer and isServer() then return end

local function isPvE(targ)
    if not targ then return false end
    if ParadiseZ.isPvE then return ParadiseZ.isPvE(targ) == true end
    return targ.HasTrait and targ:HasTrait("PvE") == true or false
end

local function hasScareCrow(targ)
    if not targ then return false end
    if ParadiseZ.isScareCrow then return ParadiseZ.isScareCrow(targ) == true end
    if targ.getVariableBoolean and targ:getVariableBoolean("isScareCrow") then return true end
    if not targ.getWornItems then return false end
    local wornItems = targ:getWornItems()
    if not wornItems then return false end
    for i = 0, wornItems:size() - 1 do
        local item = wornItems:get(i):getItem()
        if item and item:getFullType() == "Skin.ScareCrow" then return true end
    end
    return false
end

function ParadiseZ.isShowTag()
    local settings = SandboxVars and SandboxVars.ParadiseZ
    return (settings and settings.ShowPvETag) or (getCore and getCore():getDebug()) or false
end

local function isAdminViewer()
    local pl = getPlayer and getPlayer() or nil
    return pl and pl.getAccessLevel and string.lower(tostring(pl:getAccessLevel())) == "admin" or false
end

local function isSuspect(targ)
    local role = targ and targ.getRole and targ:getRole() or nil
    return role and role:getName() == "Suspect" or false
end

function ParadiseZ.setSuspectTag(targ)
    local key = targ and targ.getOnlineID and targ:getOnlineID() or nil
    if not key or not isAdminViewer() or not isSuspect(targ) then
        if key then ParadiseZ.suspectTags[key] = nil end
        return
    end
    local data = ParadiseZ.suspectTags[key]
    if not data then
        local tag = TextDrawObject.new()
        tag:setDefaultFont(UIFont.NewLarge)
        tag:ReadString(UIFont.NewLarge, "SUSPECT", -1)
        tag:setDefaultColors(1, 0, 0)
        tag:setVisibleRadius(360)
        data = { tag = tag, target = targ }
        ParadiseZ.suspectTags[key] = data
    else
        data.target = targ
    end
end

function ParadiseZ.renderSuspectTags()
    if not isIngameState() or not isAdminViewer() then return end
    local now = getTimestampMs()
    if not ParadiseZ.suspectTagCheckAt or now - ParadiseZ.suspectTagCheckAt >= 1000 then
        ParadiseZ.suspectTagCheckAt = now
        local cell = getCell and getCell() or nil
        local players = cell and cell:getObjectListForLua() or nil
        if players then
            for index = 0, players:size() - 1 do
                local targ = players:get(index)
                if targ and instanceof(targ, "IsoPlayer") then ParadiseZ.setSuspectTag(targ) end
            end
        end
    end
    local zoom = getCore():getZoom(0)
    for key, data in pairs(ParadiseZ.suspectTags) do
        local targ = data.target
        if not targ or not isSuspect(targ) then
            ParadiseZ.suspectTags[key] = nil
        else
            local screenX = (IsoUtils.XToScreen(targ:getX(), targ:getY(), targ:getZ(), 0) - IsoCamera.getOffX()) / zoom
            local screenY = (IsoUtils.YToScreen(targ:getX(), targ:getY(), targ:getZ(), 0) - IsoCamera.getOffY()) / zoom - 56
            data.tag:AddBatchedDraw(screenX, screenY, 1, 0, 0, 1, false)
        end
    end
end
Events.OnPostRender.Remove(ParadiseZ.renderSuspectTags)
Events.OnPostRender.Add(ParadiseZ.renderSuspectTags)

function ParadiseZ.removeTag(targ)
    if targ then
        targ:clearAttachedAnimSprite()
    end
end

function ParadiseZ.isTagEmpty(targ)
    if not targ or not targ.getAttachedAnimSprite then return true end
    local sprites = targ:getAttachedAnimSprite()
    return not sprites or sprites:isEmpty()
end

function ParadiseZ.setTag(targ)
    if not ParadiseZ.isShowTag() then return end
    if not targ then targ = getPlayer() end
    --ParadiseZ.removeTag(targ)
    local spr
    local user = targ:getUsername() 
    if isPvE(targ) then
        spr = getSprite("media/ui/Tags/PvE_Tag.png"):newInstance()
    end
    if user and user == "Glytch3r" then
        local scareCrow = hasScareCrow(targ)
        targ:setVariable("isScareCrow", scareCrow)
        spr = getSprite("media/ui/Tags/Glytch3r_Tag.png"):newInstance()
    end
    if spr then
        targ:setAttachedAnimSprite(ArrayList.new())
        targ:getAttachedAnimSprite():add(spr)
    end
end

function ParadiseZ.setTempTag(targ)
    if not targ then targ = getPlayer() end
    if not ParadiseZ.isTagEmpty(targ) then return end
    if isPvE(targ) then return end
    local spr = getSprite("media/ui/Tags/Glytch3r_Tag.png"):newInstance()
    if spr then
        targ:setAttachedAnimSprite(ArrayList.new())
        targ:getAttachedAnimSprite():add(spr)
    end
    timer:Simple(3, function() 
        ParadiseZ.removeTag(targ)
    end)
end
function ParadiseZ.isShouldShow(targ)
    local pl = getPlayer()
    if pl and targ and ((pl.CanSee and pl:CanSee(targ)) or pl == targ) then
        local x, y = targ:getX(), targ:getY()
        return x and y
    end
    return false
end

function ParadiseZ.doTagCheck(targ)
    ParadiseZ.setSuspectTag(targ)
    if ParadiseZ.isShouldShow(targ) then
        ParadiseZ.setTag(targ)
    else
        if not ParadiseZ.isTagEmpty(targ)then
            ParadiseZ.removeTag(targ)
        end
    end
end

function ParadiseZ.tagHandler()
    local pl = getPlayer()
    if not pl or not getCell then return end
    local rangeSquared = 15^2
    local cell = getCell()
    if not cell then return end
    local players = cell:getObjectListForLua()
    if not players then return end

    for i = players:size(), 1, -1 do
        local targ = players:get(i - 1)
        if targ and instanceof(targ, "IsoPlayer") then
            local dist = targ.DistToSquared and targ:DistToSquared(pl) or 0
            if dist <= rangeSquared or pl == targ then
                ParadiseZ.doTagCheck(targ)
            end
        end
    end
end

Events.EveryOneMinute.Remove(ParadiseZ.tagHandler)
Events.EveryOneMinute.Add(ParadiseZ.tagHandler)


function ParadiseZ.init()
    local pl = getPlayer()
    if not pl then return end
    local user = pl:getUsername() 
    if isPvE(pl) or (user and user == "Glytch3r") then
        ParadiseZ.doTagCheck(pl)
        --ParadiseZ.disabler()
    end
end

Events.OnCreatePlayer.Remove(ParadiseZ.init)
Events.OnCreatePlayer.Add(ParadiseZ.init)
