JimsServerRules.DEFAULT_RULES = [[# SECTION 1 - WORLD, THEME & SETTING
## 1. World & Setting
This is a brutal world, but it is still meant to be fun. The rules below exist to keep things harsh in-game without letting it turn miserable outside the screen.

### Old World Religions & Politics
The old world is gone, and so are its religions and politics. New ones may be formed by the players, so please do not bring real-world religions or politics into the game or our spaces.

# SECTION 2 - SAFE ZONES, SAFEHOUSES & LOOT LOCATIONS
## 2. Safehouse Sanctuary
No attacking or killing players at their safehouses.

Do not camp the doorway, windows, or immediate area just to catch someone coming or going. Camping just outside of safehouses is against the rules everywhere.

Safehouses are meant to be a place where people can park their character, sort their stuff, and breathe. If you are trying to score easy kills off a safehouse door, you are in the wrong.

You also may not claim a safehouse in certain high-value locations:
- Malls
- Hospitals
- Police Stations
- Gun Stores
- Video Stores
- Schools
- Factories
- Military Facilities
- Fire Stations

These spots are meant to stay active and contested, not locked down as private homes.

### Commercial Buildings & Businesses
Commercial buildings in general can be valuable loot pools. Admins strategically restore loot in some of these spaces over time to keep the world feeling alive.

Do not claim a commercial building as a private safehouse unless you can provide equal or greater value to the server in your care. If you want to run a bar, shop, clinic, auction house, or any other business out of a commercial location, reach out to the admins first so we can work with you instead of against you.

## 3. Property & Personal Items
Journals and personal keys must be left behind for the player to collect.

Do not steal or destroy other players' journals. Do not take personal keys from a body or container; leave them so the owner can get them back.

This applies everywhere, including RC. Keyrings (empty keychains) may still be taken as trophies. Take loot if you want. Just do not take the stuff someone literally needs to continue their run.

# SECTION 3 - PVP, KOS ZONES & REPUTATION
## 4. PVP, KOS Zones & Consequences
PVP is permitted almost everywhere, but this is a living world. Murder, ambushes, and robberies are part of the game. So are revenge, bounty hunting, and alliances. If you choose violence, expect consequences.

## 5. Louisville KOS With Consequence
Louisville (LV) is also KOS-allowed, but it carries consequences.

If you KOS someone in LV, they are free to:
- Call in friends, factions, and reinforcements.
- Spread the word about what you did and how you play.
- Put bounties on you or refuse to trade or work with you.

Your choices in LV can shape your reputation across the rest of Paradise. People remember names, stories, and who shows up on which side of the barrel.

What happens in LV might haunt you.

Abusing KOS in LV purely to bully or farm weaker players for easy kills is a good way to get staff eyes on you.

## 6. No Griefing, Only Reputation
Griefing is not allowed. This includes, but is not limited to:
- Harassing the same player over and over in a personal way.
- Blocking entrances or access routes purely to annoy people.
- Destroying placed base-building items with no real purpose.
- Endless spawn-camping of the same player.

If you want a name for yourself, do it with smart play and memorable moves - not by making the game unplayable for someone else.

# SECTION 4 - CONDUCT, PERSONAS & DISCORD
## 7. Personas vs. People
It is fine to play a rough, rude, or hostile persona in-game. It is not fine to attack or harass the real person behind the screen.

You are free to:
- Play bandits, raiders, cultists, crime bosses, and general jerks as your in-game persona.
- Trash talk and banter, as long as it is clearly about the game and meant in good faith.

The line is crossed when:
- You insult or attack the person, not the situation.
- You keep going after someone in chat because you are mad about a death or loss.
- You try to excuse genuinely toxic behavior with "that is just my character."

Playing an asshole is not an excuse to be an asshole.

If things get heated, step back. If it is more than you can solve calmly, use tickets instead of turning chat into a shouting match.

## 8. Discord & Community Conduct
These rules do not stop at the game client - they apply on Discord too.

- Do not harass other members in channels or DMs.
- Do not dogpile, stalk, or stir up mobs against people over in-game events.
- Keep the same baseline: we are here to enjoy the game and the community, not wreck it.

Discord Terms of Service and Community Guidelines fully apply. If you break Discord's Terms of Service in our spaces, you may be removed, and serious issues may be reported to Discord.

Slurs, repeated harassment, and hate speech are taken seriously, in-game and on Discord. If you would not stand by what you are saying in front of the whole community, think twice before posting it.

# SECTION 5 - DEATH, LOSS, SPORTSMANSHIP & CHEATING
## 9. Death, Loss & Sportsmanship
This is Project Zomboid. Death and loss are part of the deal.

Getting killed in PVP, robbed, or having your base raided is not automatically a rules issue. Dying in a crash, crossfire, mis-aimed shot, or panic moment is part of the chaos.

None of that is a free pass to blow up, get personal, or start swinging at people in chat.

Trash talk is allowed within reason, with the understanding that:
- All trash talk should be in good faith and clearly about the game.
- Everyone is assumed to intend no personal offence.
- If someone says a line has been crossed, ease off.

We are here to have a good time together, not to make somebody log off angry.

## 10. Sportsmanship, Fair Play & Cheating
1v1s, duels, and organized events are encouraged - set them up in chat and respect the outcome.

- No hacks, exploits, scripts, or third-party cheats.
- No alt accounts to scout, grief, or dodge consequences.
- No dupes, unfair macros, or anything that gives you a hidden edge.

Cheaters will be banned and reported to Steam. Cheaters wreck the experience for everyone. If you are caught, you are gone.

If you suspect a cheater, do not start a public witch-hunt:
- Collect evidence: video, screenshots, audio, and logs.
- Send it through the proper channels described in Contacting Staff & Tickets below.

# SECTION 6 - CONTACTING STAFF & TICKETS
## 11. Do Not Page Admins in All-Chat
Please do not rely on global/all-chat to get admin attention. Messages scroll by, get buried, and we may not see them in time.

## 12. Use the In-Game Ticket System
The fastest way to reach staff in-game:
- Open the Client menu on the left side of your screen.
- Click Tickets.
- Create a ticket with a clear description of what is going on.

Tickets come with context and logs, which makes it much easier for us to help you.

## 13. Use the Right Discord Channels
For mod issues or glitches, post in #mod-issues-and-error-reports.

Be clear: what happened, where, when, and what you were doing.

For serious issues needing urgent attention - rule breaks, griefing, or major bugs - open a ticket in #help-tickets on Discord and explain the situation.

For suspected cheaters, include video, screenshots, audio, and any other details that help us verify.

# SECTION 7 - ADMINS, SCENES & ABUSE REPORTING
## 14. Admins on Scene
If an admin shows up near you or teleports into a scene and you do not know why:
- First, get yourself safe from zombies and world hazards.
- Then take a second to see if the admin needs your attention - stop, listen, and respond.
- Treat staff like you would any other player, plus a bit of respect for the work they are doing.

Our kindness is not a weakness.

Staff are here to keep the world running and the stories flowing. They should be treated with the same respect you expect in return.

Ignoring reasonable requests from staff or making their job harder on purpose can have consequences.

## 15. Admin Conduct & Reporting Abuse
Most of what admins do is quiet, unflashy, and necessary to keep the server going.

An admin using tools to moderate, investigate, teleport, freeze, kick, or ban within their role is not admin abuse.

They do not work for individual players - they work for the health of the server as a whole.

We will get to issues as fast as we realistically can, but an admin not helping you immediately is not admin abuse.

Real admin abuse looks different:
- Using powers to harass you with clear bad intent.
- Repeatedly targeting you without cause and outside normal moderation.

If you think you are dealing with actual admin abuse:
- Stay as calm as you can and save evidence: video, screenshots, and chat logs.
- Open a ticket in #help-tickets or via Client Tickets with a clear description and the evidence.

It will be reviewed by the appropriate staff or owners.

Throwing around "admin abuse" every time you dislike a fair decision is not helpful and may itself become an issue.

# SECTION 8 - PLAY STYLES, ENFORCEMENT & FINAL WORD
## 16. Play Your Way
Build, trade, sneak, fight, or roleplay - all playstyles are welcome as long as you stay within these guidelines.

Remember the spirit:
We survive together, or we perish alone.

## 17. Enforcement
First offense:
- Warning and a short mute or kick if needed.

Repeat or serious issues - cheating, heavy harassment, targeted griefing, and similar behavior:
- Temporary ban or permanent ban at admin discretion.

Cheaters will be permanently banned and reported to Steam.

Staff make judgment calls with the whole community in mind.

## 18. Final Word
We are all here because we like this game and the stories it lets us tell.

The bottom line: Do not be a dick.

Play hard. Play fair. Play together.

Welcome to Paradise.
Let the stories begin.]]
