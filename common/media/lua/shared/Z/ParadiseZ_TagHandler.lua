function ParadiseZ.getTagLineHeight(font)
    return getTextManager():getFontHeight(font) + ParadiseZ.tagSpacer
end

function ParadiseZ.getTagScreenPos(targ, offsetY, tagHeight)
    local zoom = getCore():getZoom(0)
    local screenPos = ParadiseZ.tagScreenPos
    local car = targ:getVehicle()
    if not car or not car:getNameCoordForPlayer(targ, zoom, screenPos) then
        IsoGameCharacter.getNameCoords(targ:getX(), targ:getY(), targ:getZ(), targ:getOffsetX(), targ:getOffsetY() + ParadiseZ.tagHeadOffset, zoom, screenPos)
    end
    local screenX = screenPos:getX()
    local screenY = screenPos:getY() - ParadiseZ.getTagLineHeight(UIFont.Small) - (offsetY or 0) - (tagHeight or 0)
    return math.floor(screenX + 0.5), math.floor(screenY + 0.5)
end

local function isPvE(targ)
    if not targ then return false end
    if ParadiseZ.isPvE then return ParadiseZ.isPvE(targ) == true end
    return ParadiseDev and ParadiseDev.hasTrait and ParadiseDev.hasTrait(targ, "ParadiseDev:PvE") == true or false
end

local function isCaged(targ)
    if not targ then return false end
    if targ.HasTrait then return targ:HasTrait("ParadiseDev:Caged") == true end
    if ParadiseDev and ParadiseDev.Cage and ParadiseDev.Cage.isTargetCaged then
        return ParadiseDev.Cage.isTargetCaged(targ) == true
    end
    local traits = targ.getCharacterTraits and targ:getCharacterTraits() or nil
    return traits and traits.contains and traits:contains("ParadiseDev:Caged") == true or false
end

local function hasScareCrow(targ)
    if not targ then return false end
    if ParadiseZ.isScareCrow then return ParadiseZ.isScareCrow(targ) == true end
    if targ.getVariableBoolean and targ:getVariableBoolean("isScareCrow") then return true end
    if not targ.getWornItems then return false end
    local wornItems = targ:getWornItems()
    if not wornItems then return false end
    for i = 0, wornItems:size() - 1 do
        local item = wornItems:get(i):getItem()
        if item and item:getFullType() == "Skin.ScareCrow" then return true end
    end
    return false
end

function ParadiseZ.isShowTag()
    local settings = SandboxVars and SandboxVars.ParadiseZ
    return (settings and settings.ShowPvETag) or (getCore and getCore():getDebug()) or false
end

function ParadiseZ.isModdedAdminTagEnabled()
    local settings = SandboxVars and SandboxVars.ParadiseZ
    return not settings or settings.ShowModdedAdminTag ~= false
end

function ParadiseZ.getAdminTagState(targ)
    if not targ then return false end
    local user = targ.getUsername and targ:getUsername() or nil
    local synced = user and ParadiseZ.adminTagStates[string.lower(tostring(user))] or nil
    if synced ~= nil then return synced == true end
    local modData = targ:getModData()
    if modData.ParadiseZShowAdminTag == nil then modData.ParadiseZShowAdminTag = true end
    return modData.ParadiseZShowAdminTag == true
end

function ParadiseZ.isShowAdminTag(targ)
    if not ParadiseZ.isModdedAdminTagEnabled() then return false end
    if not targ or not ParadiseRestore or not ParadiseRestore.isAdm then return false end
    if not ParadiseRestore.isAdm(targ) then return false end
    if targ.isInvisible and targ:isInvisible() then return false end
    return ParadiseZ.getAdminTagState(targ)
end

ParadiseZ.calculateShowAdminTagHook = ParadiseZ.calculateShowAdminTagHook or IsoPlayer.calculateShowAdminTag
function IsoPlayer:calculateShowAdminTag()
    if ParadiseZ.isShowAdminTag(self) then return false end
    return ParadiseZ.calculateShowAdminTagHook(self)
end

function ParadiseZ.toggleShowAdminTag(targ)
    if not ParadiseRestore.isAdm(targ) then return end
    local modData = targ:getModData()
    modData.ParadiseZShowAdminTag = not ParadiseZ.getAdminTagState(targ)
    local user = targ.getUsername and targ:getUsername() or nil
    if user then ParadiseZ.adminTagStates[string.lower(tostring(user))] = modData.ParadiseZShowAdminTag end
    if targ.transmitModData then targ:transmitModData() end
    if isClient and isClient() and sendClientCommand then
        sendClientCommand("ParadiseZTagHandler", "setAdminTagState", { shown = modData.ParadiseZShowAdminTag })
    end
end

function ParadiseZ.applyAdminTagState(user, shown)
    if not user then return end
    ParadiseZ.adminTagStates[string.lower(tostring(user))] = shown == true
    local targ = getPlayerFromUsername and getPlayerFromUsername(tostring(user)) or nil
    if not targ then return end
    targ:getModData().ParadiseZShowAdminTag = shown == true
    ParadiseZ.setTag(targ)
end

function ParadiseZ.onTagServerCommand(module, command, args)
    if module ~= "ParadiseZTagHandler" or not args then return end
    if command == "adminTagState" then
        ParadiseZ.applyAdminTagState(args.user, args.shown)
    elseif command == "adminTagStates" then
        ParadiseZ.adminTagStates = args.states or {}
    end
end
