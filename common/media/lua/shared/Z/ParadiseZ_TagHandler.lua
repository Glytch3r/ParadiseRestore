    local viewer, cell = getViewer()
    if not viewer then
        if runtime.viewer or hasEntries(runtime.players) or hasEntries(ParadiseZ.survivorTags) then ParadiseZ.clearTagCaches(false) end
        if not isIngameState() and runtime.sessionViewer then ParadiseZ.clearTagCaches(true) end
        return nil
    end
    if runtime.sessionViewer ~= viewer then
        ParadiseZ.clearTagCaches(true)
        runtime.sessionViewer = viewer
    end
    if runtime.viewer ~= viewer or runtime.cell ~= cell then
        ParadiseZ.clearTagCaches(false)
        runtime.viewer, runtime.cell = viewer, cell
    end
    if isClient and isClient() and not runtime.adminReady then
        local now, previous = getTimestampMs(), runtime.lastRequestAt
        if not previous or now < previous or now - previous >= 5000 then ParadiseZ.requestAdminTagState() end
    end
    return viewer, cell
end

function ParadiseZ.tagHandler()
    local viewer, cell = prepareSession()
    if not viewer then return end
    ParadiseZ.refreshOnlinePlayers(true)
    for target in pairs(runtime.players) do
        if not validTarget(target, viewer, cell, false) then ParadiseZ.removeTag(target) end
    end
    for target in pairs(ParadiseZ.onlinePlayers) do
        if validTarget(target, viewer, cell, false) then ParadiseZ.setTag(target) end
    end
end

function ParadiseZ.updateTagHandler()
    if not prepareSession() then return end
    local now, previous = getTimestampMs(), ParadiseZ.lastTagHandlerAt
    if not previous or now < previous or now - previous >= ParadiseZ.getTagHandlerRefreshRate() * 1000 then
        ParadiseZ.lastTagHandlerAt = now
        ParadiseZ.tagHandler()
    end
    if ParadiseZ.isAdminViewer() then
        local checked = ParadiseZ.survivorTagCheckAt
        if not checked or now < checked or now - checked >= 500 then
            ParadiseZ.survivorTagCheckAt = now
            ParadiseZ.updateSurvivorTags()
        end
    else
        empty(ParadiseZ.survivorTags)
        ParadiseZ.survivorTagCheckAt = nil
    end
end

local function drawPlayerTags(viewer, cell, kind)
    local now = getTimestampMs()
    for target, record in pairs(runtime.players) do
        if record.id ~= target:getOnlineID() or not validTarget(target, viewer, cell, false) then
            ParadiseZ.removeTag(target)
        elseif (hasEntries(record.tags) or record.tempUntil) and visibleTarget(target, viewer) then
            local screenX, screenY = ParadiseZ.getTagScreenPos(target, 0, 0)
            local offset = 0
            for _, definition in ipairs(playerTagDefinitions) do
                local data = record.tags[definition.id]
                -- Revoke settings, roles and traits before drawing, even with slow discovery.
                local enabled = data and definition.eligible(target) == true
                if data then data.enabled = enabled; publishTag(record, definition, data, enabled) end
                if enabled then
                    data.offsetY = offset
                    local tagKind = definition.id == "suspect" and "suspect" or (definition.image and "image" or "text")
                    if definition.image then
                        if (not kind or kind == tagKind) and data.texture then
                            UIManager.DrawTexture(data.texture, screenX - ParadiseZ.tagImageSize / 2, screenY - offset - ParadiseZ.tagImageSize, ParadiseZ.tagImageSize, ParadiseZ.tagImageSize, 1)
                        end
                        offset = offset + ParadiseZ.tagImageSize + ParadiseZ.tagSpacer
                    else
                        if not kind or kind == tagKind then
                            data.tag:Draw(screenX, screenY - offset - data.tag:getHeight(), definition.r, definition.g, definition.b, 1, false)
                        end
                        offset = offset + ParadiseZ.getTagLineHeight(definition.font)
                    end
                end
            end
            if record.tempUntil and now >= record.tempUntil then record.tempUntil = nil end
            if record.tempUntil and record.tempTexture and (not kind or kind == "image") then
                UIManager.DrawTexture(record.tempTexture, screenX - 16, screenY - offset - 32, 32, 32, 1)
            end
        end
    end
end

local function drawSurvivorTags(viewer, cell)
    for target, data in pairs(ParadiseZ.survivorTags) do
        if not validTarget(target, viewer, cell, true) then ParadiseZ.survivorTags[target] = nil
        elseif visibleTarget(target, viewer) then
            local x, y = ParadiseZ.getTagScreenPos(target, 0, data.tag:getHeight())
            data.tag:Draw(x, y, 1, 0.2, 0.2, 1, false)
        end
    end
end

function ParadiseZ.renderTags()
    ParadiseZ.updateTagHandler()
    local viewer, cell = getViewer()
    if not viewer then return end
    drawPlayerTags(viewer, cell)
    drawSurvivorTags(viewer, cell)
end

-- Callable compatibility entry points; only renderTags is registered.
function ParadiseZ.renderPublicTextTags()
    local viewer, cell = prepareSession()
    if viewer then drawPlayerTags(viewer, cell, "text") end
end
function ParadiseZ.renderPublicImageTags()
    local viewer, cell = prepareSession()
    if viewer then drawPlayerTags(viewer, cell, "image") end
end
function ParadiseZ.renderSuspectTags()
    local viewer, cell = prepareSession()
    if viewer then drawPlayerTags(viewer, cell, "suspect") end
end
function ParadiseZ.renderSurvivorTags()
    local viewer, cell = prepareSession()
    if viewer then drawSurvivorTags(viewer, cell) end
end
function ParadiseZ.renderOwnTag()
    -- Own tags share the main record/pass; no separate drawing is necessary.
end

function ParadiseZ.applyAdminTagState(username, shown)
    if type(username) ~= "string" or type(shown) ~= "boolean" then return end
    ParadiseZ.adminTagStates[string.lower(username)] = shown
    local target = getPlayerFromUsername and getPlayerFromUsername(username) or nil
    if target then
        target:getModData().ParadiseZShowAdminTag = shown
        ParadiseZ.setTag(target)
    end
end

function ParadiseZ.onTagServerCommand(module, command, args)
    if module ~= "ParadiseZTagHandler" or type(args) ~= "table" then return end
    if command == "adminTagState" then
        ParadiseZ.applyAdminTagState(args.user, args.shown)
    elseif command == "adminTagStates" and type(args.states) == "table" then
        -- Validate the complete snapshot before enabling remote admin labels.
        for username, shown in pairs(args.states) do
            if type(username) ~= "string" or type(shown) ~= "boolean" then return end
        end
        empty(ParadiseZ.adminTagStates)
        for username, shown in pairs(args.states) do ParadiseZ.adminTagStates[string.lower(username)] = shown end
        runtime.adminReady = true
        ParadiseZ.lastTagHandlerAt = nil
    end
end

function ParadiseZ.toggleShowAdminTag(target)
    if not target or not ParadiseRestore or not ParadiseRestore.isAdm or not ParadiseRestore.isAdm(target) then return end
    if isClient and isClient() and (target ~= getPlayer() or not runtime.adminReady) then return end
    local shown = not ParadiseZ.getAdminTagState(target)
    if isClient and isClient() then
        -- Only the sender's own optimistic preference changes; the existing
        -- authenticated server command remains authoritative for other viewers.
        if not sendClientCommand then return end
        ParadiseZ.applyAdminTagState(target:getUsername(), shown)
        sendClientCommand("ParadiseZTagHandler", "setAdminTagState", { shown = shown })
    else
        ParadiseZ.applyAdminTagState(target:getUsername(), shown)
        target:getModData().ParadiseZShowAdminTag = shown
    end
end

ParadiseZ.calculateShowAdminTagHook = ParadiseZ.calculateShowAdminTagHook or IsoPlayer.calculateShowAdminTag
function IsoPlayer:calculateShowAdminTag()
    local record = runtime.players[self]
    local data = record and record.tags.ADMIN
    if data and ParadiseZ.isShowAdminTag(self) and ParadiseZ.isShouldShow(self) and string.lower(tostring(self:getAccessLevel())) == "admin" then return false end
    return ParadiseZ.calculateShowAdminTagHook(self)
end

function ParadiseZ.onCharacterDeath(target)
    ParadiseZ.removeTag(target)
    if target == getPlayer() then ParadiseZ.clearTagCaches(false) end
end

function ParadiseZ.onTagSessionEnd() ParadiseZ.clearTagCaches(true) end

function ParadiseZ.init()
    local viewer = getPlayer and getPlayer() or nil
    if runtime.sessionViewer ~= viewer then
        ParadiseZ.clearTagCaches(true)
        runtime.sessionViewer = viewer
    else ParadiseZ.clearTagCaches(false) end
    if viewer and not runtime.adminReady and not runtime.lastRequestAt then ParadiseZ.requestAdminTagState() end
end

