local function makeText(text, font, r, g, b)
    local tag = TextDrawObject.new()
    tag:setDefaultFont(font)
    tag:ReadString(font, text, -1)
    tag:setDefaultColors(r, g, b)
    return tag
end

local function publishTag(record, definition, data, enabled)
    data.key = data.key or (tostring(record.id) .. ":" .. definition.id)
    local key = data.key
    if definition.id == "suspect" then
        if enabled then ParadiseZ.suspectTags[record.id] = data
        elseif ParadiseZ.suspectTags[record.id] == data then ParadiseZ.suspectTags[record.id] = nil end
    elseif definition.image then
        if enabled then ParadiseZ.publicImageTags[key] = data
        elseif ParadiseZ.publicImageTags[key] == data then ParadiseZ.publicImageTags[key] = nil end
    else
        if enabled then ParadiseZ.publicTextTags[key] = data
        elseif ParadiseZ.publicTextTags[key] == data then ParadiseZ.publicTextTags[key] = nil end
    end
end

function ParadiseZ.removeTag(target)
    if not target then return end
    local record = runtime.players[target]
    if record then
        for _, definition in ipairs(playerTagDefinitions) do
            local data = record.tags[definition.id]
            if data then publishTag(record, definition, data, false) end
        end
        runtime.players[target] = nil
    end
    ParadiseZ.survivorTags[target] = nil
    -- Never clear attached sprites owned by the engine or another mod.
end

local function updateRecord(record)
    for _, definition in ipairs(playerTagDefinitions) do
        local enabled = definition.eligible(record.target) == true
        local data = record.tags[definition.id]
        if enabled and not data then
            data = { target = record.target, definition = definition }
            if definition.image then data.texture = getTexture(definition.image)
            else data.tag = makeText(definition.text, definition.font, definition.r, definition.g, definition.b) end
            record.tags[definition.id] = data
        end
        if data then data.enabled = enabled; publishTag(record, definition, data, enabled) end
    end
end

function ParadiseZ.setTag(target)
    target = target or getPlayer()
    local viewer, cell = getViewer()
    if not viewer or not validTarget(target, viewer, cell, false) then ParadiseZ.removeTag(target); return end
    local record = runtime.players[target]
    if not record or record.id ~= target:getOnlineID() then
        if record then ParadiseZ.removeTag(target) end
        record = { target = target, id = target:getOnlineID(), tags = {} }
        runtime.players[target] = record
    end
    updateRecord(record)
    if target:getUsername() == "Glytch3r" and target.setVariable then target:setVariable("isScareCrow", hasScareCrow(target)) end
end
function ParadiseZ.setSuspectTag(target) ParadiseZ.setTag(target) end
function ParadiseZ.doTagCheck(target) ParadiseZ.setTag(target) end

function ParadiseZ.isTagEmpty(target)
    local record = target and runtime.players[target] or nil
    if not record then return true end
    if record.tempUntil and getTimestampMs() < record.tempUntil then return false end
    for _, data in pairs(record.tags) do if data.enabled then return false end end
    return true
end

function ParadiseZ.setTempTag(target)
    target = target or getPlayer()
    if not target or isPvE(target) or not ParadiseZ.isTagEmpty(target) then return end
    ParadiseZ.setTag(target)
    local record = runtime.players[target]
    if not record then return end
    record.tempTexture = record.tempTexture or getTexture("media/ui/Tags/Glytch3r_Tag.png")
    record.tempUntil = getTimestampMs() + 3000
end

local function getSurvivorName(target)
    local tracker = ParadiseRestore and ParadiseRestore.DeadTracker
    local name = tracker and tracker.getOwnerUsername and tracker.getOwnerUsername(target) or nil
    if not name or name == "" then name = target.getUsername and target:getUsername() or nil end
    if not name or name == "" then name = target.getPlayerName and target:getPlayerName() or nil end
    if not name or name == "" then name = target.getName and target:getName() or nil end
    local data = target.getModData and target:getModData() or nil
    if (not name or name == "") and data then name = data.ParadiseRestoreDeadPlayerUsername or data.username or data.Username or data.playerName end
    return name and tostring(name) or "Unknown"
end

function ParadiseZ.setSurvivorTag(target)
    local viewer, cell = getViewer()
    if not viewer or not validTarget(target, viewer, cell, true) then return end
    local name, data = getSurvivorName(target), ParadiseZ.survivorTags[target]
    if not data then
        ParadiseZ.survivorTags[target] = { target = target, name = name, tag = makeText(name, UIFont.Small, 1, 0.2, 0.2) }
    elseif data.name ~= name then
        data.name = name
        data.tag:ReadString(UIFont.Small, name, -1)
    end
end

function ParadiseZ.updateSurvivorTags()
    if not ParadiseZ.isAdminViewer() then empty(ParadiseZ.survivorTags); return end
    local viewer, cell = getViewer()
    if not viewer then empty(ParadiseZ.survivorTags); return end
    -- Preserve existing discovery scope. Ordinary static corpses are not in
    -- the native moving-object list; explicit setSurvivorTag remains supported.
    local objects = cell.getObjectListForLua and cell:getObjectListForLua() or nil
    if objects then
        for index = 0, objects:size() - 1 do
            local target = objects:get(index)
            if isSurvivor(target) then ParadiseZ.setSurvivorTag(target) end
        end
    end
    for target in pairs(ParadiseZ.survivorTags) do
        if not validTarget(target, viewer, cell, true) then ParadiseZ.survivorTags[target] = nil end
    end
end

function ParadiseZ.requestAdminTagState()
    if isClient and isClient() and sendClientCommand then
        runtime.lastRequestAt = getTimestampMs()
        sendClientCommand("ParadiseZTagHandler", "requestAdminTagState", {})
    end
end

