function ParadiseZ.clearTagCaches(clearAdminStates)
    runtime.players = {}
    runtime.viewer, runtime.cell = nil, nil
    ParadiseZ.publicTextTags, ParadiseZ.publicImageTags = {}, {}
    ParadiseZ.suspectTags, ParadiseZ.survivorTags = {}, {}
    ParadiseZ.ownTagTextures, ParadiseZ.onlinePlayers = {}, {}
    ParadiseZ.onlinePlayersCheckedAt, ParadiseZ.lastTagHandlerAt, ParadiseZ.survivorTagCheckAt = nil, nil, nil
    if clearAdminStates ~= false then
        ParadiseZ.adminTagStates = {}
        runtime.adminReady = false
        runtime.sessionViewer, runtime.lastRequestAt = nil, nil
    end
end
ParadiseZ.clearTagCaches(true)

function ParadiseZ.getTagHandlerRefreshRate()
    local settings = SandboxVars and SandboxVars.ParadiseZ
    local value = tonumber(settings and settings.TagHandlerRefreshRate) or 0.10
    if value ~= value then value = 0.10 end
    return math.max(0.10, math.min(60.00, value))
end

function ParadiseZ.getTagLineHeight(font)
    return getTextManager():getFontHeight(font) + ParadiseZ.tagSpacer
end

function ParadiseZ.getTagScreenPos(target, offsetY, tagHeight)
    local zoom = getCore():getZoom(0)
    local position = ParadiseZ.tagScreenPos
    local car = target.getVehicle and target:getVehicle() or nil
    if not car or not car:getNameCoordForPlayer(target, zoom, position) then
        IsoGameCharacter.getNameCoords(target:getX(), target:getY(), target:getZ(), target:getOffsetX(), target:getOffsetY() + ParadiseZ.tagHeadOffset, zoom, position)
    end
    local y = position:getY() - ParadiseZ.getTagLineHeight(UIFont.Small) - (offsetY or 0) - (tagHeight or 0)
    return math.floor(position:getX() + 0.5), math.floor(y + 0.5)
end

local function isPvE(target)
    if ParadiseZ.isPvE then return ParadiseZ.isPvE(target) == true end
    return ParadiseDev and ParadiseDev.hasTrait and ParadiseDev.hasTrait(target, "ParadiseDev:PvE") == true or false
end

local function isCaged(target)
    if target.HasTrait then return target:HasTrait("ParadiseDev:Caged") == true end
    if ParadiseDev and ParadiseDev.Cage and ParadiseDev.Cage.isTargetCaged then
        return ParadiseDev.Cage.isTargetCaged(target) == true
    end
    local traits = target.getCharacterTraits and target:getCharacterTraits() or nil
    return traits and traits.contains and traits:contains("ParadiseDev:Caged") == true or false
end

local function hasScareCrow(target)
    if ParadiseZ.isScareCrow then return ParadiseZ.isScareCrow(target) == true end
    if target.getVariableBoolean and target:getVariableBoolean("isScareCrow") then return true end
    local worn = target.getWornItems and target:getWornItems() or nil
    if not worn then return false end
    for index = 0, worn:size() - 1 do
        local item = worn:get(index):getItem()
        if item and item:getFullType() == "Skin.ScareCrow" then return true end
    end
    return false
end

local function hasRole(target, wanted)
    local role = target and target.getRole and target:getRole() or nil
    return role and string.lower(tostring(role:getName())) == wanted or false
end

function ParadiseZ.isShowTag()
    local settings = SandboxVars and SandboxVars.ParadiseZ
    return settings ~= nil and settings.ShowPvETag == true
end

function ParadiseZ.isModdedAdminTagEnabled()
    local settings = SandboxVars and SandboxVars.ParadiseZ
    return not settings or settings.ShowModdedAdminTag ~= false
end

function ParadiseZ.getAdminTagState(target)
    if not target then return false end
    if isClient and isClient() and not runtime.adminReady then return false end
    local username = target.getUsername and target:getUsername() or nil
    local synced
    if username then synced = ParadiseZ.adminTagStates[string.lower(tostring(username))] end
    if synced ~= nil then return synced == true end
    return target:getModData().ParadiseZShowAdminTag ~= false
end

function ParadiseZ.isShowAdminTag(target)
    if not ParadiseZ.isModdedAdminTagEnabled() or not target then return false end
    if not ParadiseRestore or not ParadiseRestore.isAdm or not ParadiseRestore.isAdm(target) then return false end
    if target.isInvisible and target:isInvisible() then return false end
    return ParadiseZ.getAdminTagState(target)
end

function ParadiseZ.isAdminViewer()
    local viewer = getPlayer and getPlayer() or nil
    return viewer and viewer.getAccessLevel and string.lower(tostring(viewer:getAccessLevel())) == "admin" or false
end

function ParadiseZ.isLivePlayer(target)
    if not target or not instanceof(target, "IsoPlayer") or target:isDead() then return false end
    if not isClient or not isClient() then return target == getPlayer() end
    local id = target:getOnlineID()
    -- Native map lookup verifies exact identity even when a numeric ID is reused.
    return id ~= nil and id >= 0 and getPlayerByOnlineID and getPlayerByOnlineID(id) == target or false
end

local function isSurvivor(target)
    if not target then return false end
    if instanceof(target, "IsoDeadBody") then return target:isPlayer() == true end
    return instanceof(target, "IsoZombie") and not target:isDead() and target:isReanimatedPlayer() == true
end

local function isLoaded(target, cell)
    local square = target and target.getSquare and target:getSquare() or nil
    if not square or not cell or not cell.getGridSquare then return false end
    if cell:getGridSquare(math.floor(target:getX()), math.floor(target:getY()), math.floor(target:getZ())) ~= square then return false end
    if instanceof(target, "IsoDeadBody") then
        return target.getStaticMovingObjectIndex and target:getStaticMovingObjectIndex() >= 0 or false
    end
    return target.getMovingObjectIndex and target:getMovingObjectIndex() >= 0 or false
end

local function distanceSquared(target, viewer)
    local dx, dy = target:getX() - viewer:getX(), target:getY() - viewer:getY()
    return dx * dx + dy * dy
end

local function getViewer()
    if not isIngameState() then return nil end
    local viewer = getPlayer and getPlayer() or nil
    local cell = getCell and getCell() or nil
    if not ParadiseZ.isLivePlayer(viewer) or not isLoaded(viewer, cell) then return nil end
    return viewer, cell
end

local function validTarget(target, viewer, cell, survivor)
    if survivor then
        if not ParadiseZ.isAdminViewer() or not isSurvivor(target) then return false end
    elseif not ParadiseZ.isLivePlayer(target) then return false end
    -- Admin survivor labels retain their existing visible-world range.
    return (survivor or distanceSquared(target, viewer) <= RANGE_SQUARED) and isLoaded(target, cell)
end

local function visibleTarget(target, viewer)
    if target.isInvisible and target:isInvisible() then return false end
    if target == viewer then return true end
    -- CanSee only tests coordinate LOS, not world membership or model visibility.
    if target.getAlpha and target:getAlpha(0) <= 0 then return false end
    return viewer.CanSee and viewer:CanSee(target) == true or false
end

function ParadiseZ.isShouldShow(target)
    local viewer, cell = getViewer()
    return viewer ~= nil and validTarget(target, viewer, cell, isSurvivor(target)) and visibleTarget(target, viewer)
end

function ParadiseZ.refreshOnlinePlayers(force)
    local now, checked = getTimestampMs(), ParadiseZ.onlinePlayersCheckedAt
    if not force and checked and now >= checked and now - checked < ParadiseZ.getTagHandlerRefreshRate() * 1000 then return end
    ParadiseZ.onlinePlayersCheckedAt = now
    empty(ParadiseZ.onlinePlayers)
    if isClient and isClient() then
        local players = getOnlinePlayers and getOnlinePlayers() or nil
        if players then
            for index = 0, players:size() - 1 do ParadiseZ.onlinePlayers[players:get(index)] = true end
        end
    else
        local player = getPlayer and getPlayer() or nil
        if player then ParadiseZ.onlinePlayers[player] = true end
    end
end

