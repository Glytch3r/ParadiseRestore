    return not sprites or sprites:isEmpty()
end

function ParadiseZ.setTag(targ)
    if not targ then targ = getPlayer() end
    if not targ then return end
    local key = targ.getOnlineID and targ:getOnlineID() or nil
    if key then
        for tagKey in pairs(ParadiseZ.publicTextTags) do
            if tostring(tagKey):sub(1, #tostring(key) + 1) == tostring(key) .. ":" then
                ParadiseZ.publicTextTags[tagKey] = nil
            end
        end
        for tagKey in pairs(ParadiseZ.publicImageTags) do
            if tostring(tagKey):sub(1, #tostring(key) + 1) == tostring(key) .. ":" then
                ParadiseZ.publicImageTags[tagKey] = nil
            end
        end
    end
    local user = targ:getUsername() 
    local offsetY = 0
    if key and isPvE(targ) then
        local tag = TextDrawObject.new()
        tag:setDefaultFont(UIFont.Small)
        tag:ReadString(UIFont.Small, "PVE", -1)
        tag:setDefaultColors(0.1, 0.8, 0.25)
        tag:setVisibleRadius(360)
        ParadiseZ.publicTextTags[tostring(key) .. ":pve"] = { tag = tag, target = targ, r = 0.1, g = 0.8, b = 0.25, offsetY = offsetY }
        offsetY = offsetY + ParadiseZ.getTagLineHeight(UIFont.Small)
    end
    if key and isCaged(targ) then
        local tag = TextDrawObject.new()
        tag:setDefaultFont(UIFont.Small)
        tag:ReadString(UIFont.Small, "CAGED", -1)
        tag:setDefaultColors(1, 0.75, 0)
        tag:setVisibleRadius(360)
        ParadiseZ.publicTextTags[tostring(key) .. ":caged"] = { tag = tag, target = targ, r = 1, g = 0.75, b = 0, offsetY = offsetY }
        offsetY = offsetY + ParadiseZ.getTagLineHeight(UIFont.Small)
    end
    if key and hasRole(targ, "Staff") then
        local tag = TextDrawObject.new()
        tag:setDefaultFont(UIFont.Small)
        tag:ReadString(UIFont.Small, "STAFF", -1)
        tag:setDefaultColors(0.95, 0.55, 0.15)
        tag:setVisibleRadius(360)
        ParadiseZ.publicTextTags[tostring(key) .. ":staff"] = { tag = tag, target = targ, r = 0.95, g = 0.55, b = 0.15, offsetY = offsetY }
        offsetY = offsetY + ParadiseZ.getTagLineHeight(UIFont.Small)
    end
    if key and hasRole(targ, "Press") then
        local tag = TextDrawObject.new()
        tag:setDefaultFont(UIFont.Small)
        tag:ReadString(UIFont.Small, "PRESS", -1)
        tag:setDefaultColors(0.35, 0.75, 1)
        tag:setVisibleRadius(360)
        ParadiseZ.publicTextTags[tostring(key) .. ":press"] = { tag = tag, target = targ, r = 0.35, g = 0.75, b = 1, offsetY = offsetY }
        offsetY = offsetY + ParadiseZ.getTagLineHeight(UIFont.Small)
    end
    if key and ParadiseZ.isShowAdminTag(targ) and targ.getAccessLevel and string.lower(tostring(targ:getAccessLevel())) == "admin" then
        local tag = TextDrawObject.new()
        tag:setDefaultFont(UIFont.NewLarge)
        tag:ReadString(UIFont.NewLarge, "ADMIN", -1)
        tag:setDefaultColors(1, 0, 0)
        tag:setVisibleRadius(360)
        ParadiseZ.publicTextTags[tostring(key) .. ":ADMIN"] = {
            tag = tag, target = targ, r = 1, g = 0, b = 0,
            offsetY = offsetY
        }
        offsetY = offsetY + ParadiseZ.getTagLineHeight(UIFont.NewLarge)
    end
    if key and user and user == "Glytch3r" then
        local scareCrow = hasScareCrow(targ)
        targ:setVariable("isScareCrow", scareCrow)
        ParadiseZ.publicImageTags[tostring(key) .. ":glytch3r"] = { texture = getTexture("media/ui/Tags/Glytch3r_Tag.png"), target = targ, offsetY = offsetY }
    end
    targ:clearAttachedAnimSprite()
    if targ == getPlayer() then
        ParadiseZ.ownTagTextures = {}
        return
    end
end

function ParadiseZ.renderOwnTag()
    if not isIngameState() then return end
    local pl = getPlayer()
    if not pl or not ParadiseZ.isShouldShow(pl) then return end
    local screenX, screenY = ParadiseZ.getTagScreenPos(pl, 0)
    for index, texture in ipairs(ParadiseZ.ownTagTextures) do
        if texture then UIManager.DrawTexture(texture, screenX - 16, screenY - (index * 32), 32, 32, 1) end
    end
end
Events.OnPostRender.Remove(ParadiseZ.renderOwnTag)
Events.OnPostRender.Add(ParadiseZ.renderOwnTag)

function ParadiseZ.setTempTag(targ)
    if not targ then targ = getPlayer() end
    if not ParadiseZ.isTagEmpty(targ) then return end
    if isPvE(targ) then return end
    local spr = getSprite("media/ui/Tags/Glytch3r_Tag.png"):newInstance()
    if spr then
        targ:setAttachedAnimSprite(ArrayList.new())
        targ:getAttachedAnimSprite():add(spr)
    end
    timer:Simple(3, function() 
        ParadiseZ.removeTag(targ)
    end)
end

function ParadiseZ.isLivePlayer(targ)
    if not targ or not instanceof(targ, "IsoPlayer") then return false end
    if targ.isDead and targ:isDead() then return false end
    if not isClient or not isClient() then return true end
    return ParadiseZ.onlinePlayers[targ] == true
end

function ParadiseZ.refreshOnlinePlayers()
    if not isClient or not isClient() then return end
    local now = getTimestampMs()
    if ParadiseZ.onlinePlayersCheckedAt and now - ParadiseZ.onlinePlayersCheckedAt < ParadiseZ.getTagHandlerRefreshRate() * 1000 then return end
    ParadiseZ.onlinePlayersCheckedAt = now
    local onlinePlayers = {}
    local players = getOnlinePlayers and getOnlinePlayers() or nil
    if players then
        for index = 0, players:size() - 1 do
            onlinePlayers[players:get(index)] = true
        end
    end
    ParadiseZ.onlinePlayers = onlinePlayers
end

function ParadiseZ.isShouldShow(targ)
    if targ and instanceof(targ, "IsoPlayer") and not ParadiseZ.isLivePlayer(targ) then return false end
    local pl = getPlayer()
    if pl and targ and ((pl.CanSee and pl:CanSee(targ)) or pl == targ) then
        local x, y = targ:getX(), targ:getY()
        return x and y
    end
    return false
end

function ParadiseZ.doTagCheck(targ)
    ParadiseZ.setSuspectTag(targ)
    if ParadiseZ.isShouldShow(targ) then
        ParadiseZ.setTag(targ)
    else
        if not ParadiseZ.isTagEmpty(targ)then
            ParadiseZ.removeTag(targ)
        end
    end
end

function ParadiseZ.tagHandler()
    local pl = getPlayer()
    if not pl or not getCell then return end
    local rangeSquared = 15^2
    local cell = getCell()
    if not cell then return end
    local players = cell:getObjectListForLua()
    if not players then return end

    for i = players:size(), 1, -1 do
        local targ = players:get(i - 1)
        if targ and instanceof(targ, "IsoPlayer") then
            local dist = targ.DistToSquared and targ:DistToSquared(pl) or 0
            if dist <= rangeSquared or pl == targ then
                ParadiseZ.doTagCheck(targ)
            end
        end
    end
end

function ParadiseZ.getTagHandlerRefreshRate()
    local value = SandboxVars and SandboxVars.ParadiseZ and SandboxVars.ParadiseZ.TagHandlerRefreshRate or 0.10
    return math.max(0.10, math.min(60.00, tonumber(value) or 0.10))
end

function ParadiseZ.updateTagHandler()
    local now = getTimestampMs()
    local delay = ParadiseZ.getTagHandlerRefreshRate() * 1000
    if ParadiseZ.lastTagHandlerAt and now - ParadiseZ.lastTagHandlerAt < delay then return end
    ParadiseZ.lastTagHandlerAt = now
    ParadiseZ.tagHandler()
end
Events.OnTick.Remove(ParadiseZ.updateTagHandler)
Events.OnTick.Add(ParadiseZ.updateTagHandler)


function ParadiseZ.init()
    local pl = getPlayer()
    if not pl then return end
    local user = pl:getUsername() 
    if isPvE(pl) or (user and user == "Glytch3r") then
        ParadiseZ.doTagCheck(pl)
        --ParadiseZ.disabler()
    end
end

Events.OnCreatePlayer.Remove(ParadiseZ.init)
Events.OnCreatePlayer.Add(ParadiseZ.init)
